# -*- coding: utf-8 -*-
"""
Export IFC Per Category
========================
Exports one IFC file per 3D view previously generated by the
"Create Views by Category" tool (any View3D named "Omniverse_<Category>").

This script is intentionally thin: it only handles user interaction
(pick a setup, pick a folder, pick which views, show progress) and
delegates all Revit-API / filesystem work to the dt_common library
(lib/dt_common/) so that logic stays testable and reusable outside
this one button.

Flow
----
1.  Discover generated category views          -> dt_common.view_utils
2.  Single custom window: pick categories,      -> dt_common.ui.export_ifc_window
    tune the IFC Export Setup live in Revit's
    own native "Modify Setup" editor, and pick
    an output folder
3.  Export each view to its own IFC file,       -> dt_common.ifc_exporter
    continuing past individual failures
4.  Show a branded success/failure popup        -> dt_common.ui.result_window
"""
from pyrevit import forms, script, revit

from dt_common.view_utils import get_generated_category_views
from dt_common.ifc_exporter import IFCCategoryExporter
from dt_common.path_utils import ensure_folder_exists
from dt_common.ui.export_ifc_window import show_export_configuration
from dt_common.ui.result_window import show_result

doc = revit.doc
logger = script.get_logger()


def main():
    # ------------------------------------------------------------------
    # 1. Detect generated category views
    # ------------------------------------------------------------------
    generated_views = get_generated_category_views(doc)
    if not generated_views:
        forms.alert(
            "No generated category views were found.\n\n"
            "Run 'Create Views by Category' first.",
            title="Export IFC by Category",
        )
        script.exit()

    # ------------------------------------------------------------------
    # 2. Single custom window: category checklist (search, check-all/
    #    uncheck-all, live count), IFC Export Setup (opens Revit's own
    #    native "Modify Setup" editor on demand), and output folder.
    # ------------------------------------------------------------------
    view_by_label = {gcv.category_label: gcv for gcv in generated_views}
    chosen_labels, chosen_setup, output_folder, setup_diagnostics = show_export_configuration(
        doc, sorted(view_by_label.keys())
    )
    if not chosen_labels:
        script.exit()

    for line in setup_diagnostics:
        logger.debug("[IFC setup detection] {}".format(line))

    selected_views = [view_by_label[label] for label in chosen_labels]
    ensure_folder_exists(output_folder)

    # ------------------------------------------------------------------
    # 3. Export, one view at a time, logging + updating progress as we go.
    #    Each export is isolated inside IFCCategoryExporter so a single
    #    category failure never aborts the remaining ones.
    # ------------------------------------------------------------------
    total = len(selected_views)

    with forms.ProgressBar(title="Exporting IFC ({value} of {max_value})") as pb:

        def on_progress(index, _total, category_label):
            logger.info("Exporting category '{}' ({}/{})".format(
                category_label, index + 1, total
            ))
            pb.update_progress(index, total)

        exporter = IFCCategoryExporter(
            doc, chosen_setup, output_folder, on_progress=on_progress
        )
        results = exporter.export_all(selected_views)

        for result in results:
            if result.success:
                logger.info("  -> OK ({:.2f}s): {}".format(
                    result.duration_seconds, result.file_name
                ))
            else:
                logger.error("  -> FAILED: {} | {}".format(
                    result.category_name, result.message
                ))

        pb.update_progress(total, total)

    # ------------------------------------------------------------------
    # 4. Branded success/failure popup -- no on-screen table, no CSV
    #    file. Full per-category detail (success or failure) is still
    #    always in the pyRevit log if you need to dig further.
    # ------------------------------------------------------------------
    if not results:
        forms.alert("No categories were exported.")
        script.exit()

    failed = [r for r in results if not r.success]
    if failed:
        failure_lines = "\n".join(
            "- {}: {}".format(r.category_name, r.message) for r in failed
        )
        show_result(
            success=False,
            title="Export Finished with Failures",
            message="{} of {} categories failed:\n{}".format(
                len(failed), len(results), failure_lines
            ),
        )
    else:
        show_result(
            success=True,
            title="Export Complete",
            message="Exported {} IFC file(s) successfully.".format(len(results)),
        )


if __name__ == "__main__":
    main()
