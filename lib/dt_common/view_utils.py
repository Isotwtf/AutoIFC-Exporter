# -*- coding: utf-8 -*-
"""
Discovery of the 3D views generated by the "Create Views by Category"
tool, so the "Export IFC by Category" tool can find them without any
UI-side bookkeeping. Detection is via an Extensible Storage tag (see
dt_common.view_tag) rather than the view's name/naming convention --
that keeps view names free to be anything (e.g. the plain category
name) without affecting which views count as "generated".
"""
from Autodesk.Revit.DB import FilteredElementCollector, View3D

from dt_common.view_tag import get_tagged_category_name


class GeneratedCategoryView(object):
    """
    Thin wrapper pairing a Revit View3D with the human-readable
    category label recovered from its name. Kept separate from the
    raw View3D so downstream code (export, reporting) doesn't need to
    re-derive the label or re-filter views itself.
    """

    def __init__(self, view, category_label):
        self.view = view
        self.category_label = category_label

    @property
    def view_id(self):
        return self.view.Id

    @property
    def view_name(self):
        return self.view.Name


def get_generated_category_views(doc):
    """
    Return every non-template View3D tagged by "Create Views by
    Category" (see dt_common.view_tag), sorted by category label for
    predictable, reproducible export order (important once a project
    has hundreds of them).
    """
    results = []
    collector = FilteredElementCollector(doc).OfClass(View3D)

    for view in collector:
        if view.IsTemplate:
            continue

        category_name = get_tagged_category_name(view)
        if not category_name:
            continue

        results.append(GeneratedCategoryView(view, category_name))

    results.sort(key=lambda gcv: gcv.category_label)
    return results
