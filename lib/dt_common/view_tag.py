# -*- coding: utf-8 -*-
"""
Marks a View3D as "generated by Create Views by Category" using Revit
Extensible Storage, instead of a naming convention.

Earlier versions of this extension identified generated views purely
by a name prefix (e.g. "Omniverse_Ducts"), so "Export IFC by Category"
could find them with a simple view.Name.startswith(prefix) check and
no shared state was needed between the two tools. That broke once the
prefix requirement was dropped -- with an empty prefix, EVERY string
starts with "", so name-based detection would match every 3D view in
the project, not just generated ones.

This module replaces that mechanism: each generated view gets a small
piece of Extensible Storage data (the exact, unmodified category name)
attached directly to the view element. View names are now free to be
anything (including just the plain category name) without affecting
detection, and the stored category name is also more accurate than
before -- it's the real name, not a reconstruction from a
sanitized/safe view name.
"""
import System
from Autodesk.Revit.DB.ExtensibleStorage import Schema, SchemaBuilder, Entity, AccessLevel

_SCHEMA_GUID = System.Guid("cb565dca-56fd-46e5-9c7f-c9d3f2bef806")
_SCHEMA_NAME = "AutoIFCCategoryView"
_FIELD_CATEGORY_NAME = "CategoryName"

_schema = None


def _get_or_create_schema():
    global _schema
    if _schema is not None:
        return _schema

    existing = Schema.Lookup(_SCHEMA_GUID)
    if existing is not None:
        _schema = existing
        return _schema

    builder = SchemaBuilder(_SCHEMA_GUID)
    builder.SetSchemaName(_SCHEMA_NAME)
    builder.SetReadAccessLevel(AccessLevel.Public)
    builder.SetWriteAccessLevel(AccessLevel.Public)
    builder.AddSimpleField(_FIELD_CATEGORY_NAME, System.String).SetDocumentation(
        "The exact Revit category name this view isolates."
    )
    _schema = builder.Finish()
    return _schema


def tag_view_with_category(view, category_name):
    """
    Attach the given category_name to view as Extensible Storage data,
    marking it as a generated category-isolation view. Must be called
    inside an open transaction (it modifies the view element).
    """
    schema = _get_or_create_schema()
    entity = Entity(schema)
    entity.Set[System.String](schema.GetField(_FIELD_CATEGORY_NAME), category_name)
    view.SetEntity(entity)


def get_tagged_category_name(view):
    """
    Return the category name stored on view via tag_view_with_category,
    or None if this view was never tagged (i.e. it's not one of ours).
    """
    schema = Schema.Lookup(_SCHEMA_GUID)
    if schema is None:
        return None

    try:
        entity = view.GetEntity(schema)
    except Exception:
        return None

    if entity is None or not entity.IsValid():
        return None

    return entity.Get[System.String](schema.GetField(_FIELD_CATEGORY_NAME))
