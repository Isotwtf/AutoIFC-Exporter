# -*- coding: utf-8 -*-
"""
Discovery of the 3D views generated by the "Create Views by Category"
tool, so the "Export IFC by Category" tool can find them without any
UI-side bookkeeping (no shared file, no extensible storage -- the view
name IS the source of truth).
"""
from Autodesk.Revit.DB import FilteredElementCollector, View3D

from dt_common.constants import DT_VIEW_PREFIX


class GeneratedCategoryView(object):
    """
    Thin wrapper pairing a Revit View3D with the human-readable
    category label recovered from its name. Kept separate from the
    raw View3D so downstream code (export, reporting) doesn't need to
    re-derive the label or re-filter views itself.
    """

    def __init__(self, view, category_label):
        self.view = view
        self.category_label = category_label

    @property
    def view_id(self):
        return self.view.Id

    @property
    def view_name(self):
        return self.view.Name


def get_generated_category_views(doc):
    """
    Return every non-template View3D whose name starts with the
    DT_VIEW_PREFIX, sorted by name for predictable, reproducible
    export order (important once a project has hundreds of them).
    """
    results = []
    collector = FilteredElementCollector(doc).OfClass(View3D)

    for view in collector:
        if view.IsTemplate:
            continue
        if not view.Name.startswith(DT_VIEW_PREFIX):
            continue

        label = view.Name[len(DT_VIEW_PREFIX):] or view.Name
        results.append(GeneratedCategoryView(view, label))

    results.sort(key=lambda gcv: gcv.view_name)
    return results
